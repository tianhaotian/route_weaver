export function mapUrl(keyword, city = '') {
  const url = new URL('https://uri.amap.com/search');
  url.search = new URLSearchParams({ keyword, city, view: 'map', src: 'route_weaver', callnative: '0' }).toString();
  return url.href;
}

export function dayFromHash(hash) {
  const match = /^#day-([1-8])$/.exec(hash);
  return match ? Number(match[1]) : null;
}
